import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import { createRequire } from 'node:module';
const realRequire = createRequire(import.meta.url);
const load = (file, deps) => { const testModule = { exports: {} }; const code = ts.transpileModule(readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText; new Function('require', 'module', 'exports', code)(name => deps[name] ?? realRequire(name), testModule, testModule.exports); return testModule.exports; };
process.env.WEBFACTORY_ADMIN_USER = 'synthetic-admin';
process.env.WEBFACTORY_ADMIN_PASSWORD = 'synthetic-test-only-password';
process.env.WEBFACTORY_SESSION_SECRET = 'synthetic-local-test-session-secret-1234567890';
const jar = new Map();
const cookieStore = { get: name => jar.get(name), set: (name, value, options) => jar.set(name, { value, options }), delete: name => jar.delete(name) };
const context = { 'server-only': {}, 'next/headers': { cookies: async () => cookieStore, headers: async () => ({ get: name => name === 'origin' ? 'http://localhost:3012' : name === 'host' ? 'localhost:3012' : null }) } };
const server = load('lib/webfactory/server.ts', context);
const actions = load('app/webfactory-actions.ts', { ...context, '@/lib/webfactory/server': server, 'next/navigation': { redirect: path => { throw Error(`redirect ${path}`); } }, 'next/cache': { revalidatePath: () => {} } });
assert.equal(await server.isAdmin(), false);
const invalid = await actions.login({}, new Map([['username', 'synthetic-admin'], ['password', 'wrong']]));
assert.equal(invalid.error, 'Invalid login details.');
assert.equal(jar.has('wf_admin'), false);
await assert.rejects(() => actions.login({}, new Map([['username', 'synthetic-admin'], ['password', 'synthetic-test-only-password']])), /redirect \/admin/);
assert.equal(jar.get('wf_admin').options.httpOnly, true);
assert.equal(jar.get('wf_admin').options.sameSite, 'strict');
assert.equal(await server.isAdmin(), true);
await assert.rejects(() => actions.logout(), /redirect \/admin\/login/);
assert.equal(await server.isAdmin(), false);
await server.issueSession();
const current = jar.get('wf_admin');
const [payload, mac] = current.value.split('.');
const expired = JSON.parse(Buffer.from(payload, 'base64url').toString()); expired.exp = Date.now() - 1;
jar.set('wf_admin', { ...current, value: `${Buffer.from(JSON.stringify(expired)).toString('base64url')}.${mac}` });
