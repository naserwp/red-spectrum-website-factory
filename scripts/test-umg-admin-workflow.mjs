import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";

const load = (file, deps = {}) => {
  const testModule = { exports: {} };
  const code = ts.transpileModule(readFileSync(file, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  new Function("require", "module", "exports", code)((name) => name === "server-only" ? {} : deps[name], testModule, testModule.exports);
  return testModule.exports;
};
const domains = load("lib/customers/domains.ts");
const rules = load("lib/webfactory/slug-rules.ts");
const state = load("lib/webfactory/workflow-state.ts", { "@/lib/customers/domains": domains, "./slug-rules": rules });
const slug = "unique-management-group";
const branded = "https://preview.redspectrum.ai/unique-management-group";
assert.equal(state.canonicalBrandedPreview(slug), branded);
assert.equal(state.isCustomerFacingPreview(slug, branded), true);
assert.equal(state.isCustomerFacingPreview(slug, "https://red-spectrum-website-factory-p7shu1b9o-naserwps-projects.vercel.app/unique-management-group"), false);
assert.equal(state.isCustomerFacingPreview("unique-home-enterprise", branded), false);
const before = state.workflowSummary({ stage: "build_approved", websiteVerified: true, qaPassed: true, slug });
assert.equal(before.websiteBuilt, "Verified");
assert.equal(before.qa, "Passed");
assert.equal(before.preview, branded);
assert.equal(before.previewReady, "Not approved");
assert.equal(before.customerApproved, "Upcoming");
assert.equal(before.production, "Not published");
assert.equal(before.domain, "Not connected");
assert.equal(before.next, "Preview Ready");
assert.equal(state.canMarkPreviewReady("build_approved", false, true), false);
assert.equal(state.canMarkPreviewReady("build_approved", true, true), true);
assert.equal(state.canMarkCustomerApproved("build_approved", true, true), false);
assert.equal(state.canMarkCustomerApproved("preview_ready", false, true), false);
assert.equal(state.canMarkCustomerApproved("preview_ready", true, true), true);
const afterPreview = state.workflowSummary({ stage: "preview_ready", websiteVerified: true, qaPassed: true, slug });
assert.equal(afterPreview.previewReady, "Complete");
assert.equal(afterPreview.customerApproved, "Not approved");
assert.equal(afterPreview.next, "Customer Approved");
const complete = state.workflowSummary({ stage: "customer_approved", websiteVerified: true, qaPassed: true, slug, productionPublished: false });
assert.equal(complete.customerApproved, "Complete");
assert.equal(complete.production, "Not published");
const note = readFileSync("customers/unique-management-group/delivery/domain-cutover-tracking.md", "utf8");
for (const fact of ["66.113.136.229", "mx.siteprotect.com", "ns1.incauthorityweb.com", "ns2.incauthorityweb.com", "not recorded", "No credentials"]) assert.match(note, new RegExp(fact.replaceAll(".", "\\.")));
assert.doesNotMatch(note, /API key|password|BEGIN PRIVATE/i);
console.log("PASS: canonical preview separation, approval gating, reconciled state, and private DNS snapshot.");

const draft = { stage: 'draft', websiteVerified: false, qaPassed: false, hasBrief: true, slugConfirmed: true, previewVerified: false };
assert.equal(state.workflowSummary(draft).next, 'Build Approved');
assert.equal(state.workflowSummary({...draft, hasBrief:false}).next, 'AI Brief Generated');
assert.equal(state.workflowSummary({...draft, slugConfirmed:false}).next, 'Slug Confirmed');
const offline = state.workflowSummary({...draft,stage:'build_approved',websiteVerified:true,qaPassed:true});
assert.equal(offline.websiteBuilt,'Verified');
assert.equal(offline.identity,'Pending');
assert.equal(offline.next,'Preview Verification');
assert.equal(state.workflowSummary({...draft,stage:'customer_approved',websiteVerified:true}).customerApproved,'Complete');
console.log('PASS: earlier prerequisite precedence, build evidence independent of branded reachability, persisted approval preserved.');
