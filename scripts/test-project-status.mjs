import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const testModule = { exports: {} };
const code = ts.transpileModule(readFileSync('lib/webfactory/project-status.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
new Function('module', 'exports', code)(testModule, testModule.exports);
const { mapProjectStatus, mapAdminProjectStatus } = testModule.exports;
const source = { id: '11111111-2222-4333-8444-555555555555', business: 'Test Project', status: 'preview_ready', customer_slug: 'test-project', created_at: '2026-01-01T00:00:00Z', updated_at: '2026-01-02T00:00:00Z', stage: 'preview_ready', brief_status: 'generated', build_status: 'ready_for_review', review_status: 'preview_ready', preview_url: 'https://internal.example/private?token=secret', email: 'private@example.com', admin_notes: 'private', activity: 'internal' };
const customer = mapProjectStatus(source);
const admin = mapAdminProjectStatus(source);
assert.equal(customer.stage, 'customer_review');
assert.equal(customer.previewHref, 'https://preview.redspectrum.ai/test-project');
assert.equal(customer.approval, 'in_review');
assert.equal(customer.timeline.filter(step => step.current).length, 1);
assert.equal(customer.delivery, 'unavailable');
for (const value of ['id', 'email', 'admin_notes', 'activity', 'preview_url', 'customer_slug', 'buildStatus']) assert.equal(Object.hasOwn(customer, value), false, value);
assert.equal(admin.id, source.id);
assert.equal(admin.buildStatus, 'ready_for_review');
assert.equal(mapProjectStatus({ ...source, stage: null, status: 'received', build_status: null, review_status: null, preview_url: null }).previewHref, null);
console.log('PASS: real-state mapping, customer DTO filtering, branded preview, disabled delivery');
